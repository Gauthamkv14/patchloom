"""Cryptographic integrity verification for TestExecutionPlan (M4 VERIFY & CONTRIBUTE Pillar).

Binds execution plans generated by PatchLoom to the specific repository, issue,
allowlisted runner, commands, arguments, timeout, and expiration window.
Prevents client tampering, command injection via forged plans, and replay attacks.
"""

from datetime import datetime, timedelta, timezone
import hashlib
import hmac
import logging
import secrets
from typing import Optional

from app.config import settings
from app.github_client import InvalidGitHubURLError, parse_and_validate_github_url
from app.schemas import TestExecutionPlan

logger = logging.getLogger(__name__)

# No ephemeral fallback secret in live mode: live execution requires explicit configuration
def get_signing_secret_bytes(secret: Optional[str] = None) -> Optional[bytes]:
    """
    Retrieve configured signing secret as bytes.
    Returns None if no explicit signing secret is configured.
    """
    if secret and secret.strip():
        return secret.strip().encode("utf-8")
    if settings.EXECUTION_SIGNING_SECRET and settings.EXECUTION_SIGNING_SECRET.strip():
        return settings.EXECUTION_SIGNING_SECRET.strip().encode("utf-8")
    return None


def canonicalize_repo_url(repo_url: str) -> str:
    """Normalize repo URL to canonical lowercase https://github.com/OWNER/REPO format."""
    try:
        owner, repo_name = parse_and_validate_github_url(repo_url)
        return f"https://github.com/{owner}/{repo_name}".lower()
    except (InvalidGitHubURLError, Exception):
        return repo_url.strip().rstrip("/").lower()


def compute_plan_signature(
    repo_url: str,
    issue_number: int,
    plan: TestExecutionPlan,
    secret: Optional[str] = None,
) -> Optional[str]:
    """
    Compute HMAC-SHA256 signature binding plan parameters to repository context.
    Returns None if no signing secret is configured.
    """
    secret_bytes = get_signing_secret_bytes(secret)
    if not secret_bytes:
        return None

    canonical_repo = canonicalize_repo_url(repo_url)
    joined_args = "\t".join(str(a) for a in plan.arguments)
    expires = plan.expires_at or ""

    payload = (
        f"{canonical_repo}|"
        f"{issue_number}|"
        f"{plan.test_runner.strip().lower()}|"
        f"{plan.command.strip()}|"
        f"{joined_args}|"
        f"{plan.timeout_seconds}|"
        f"{expires}"
    )

    return hmac.new(secret_bytes, payload.encode("utf-8"), hashlib.sha256).hexdigest()


def sign_execution_plan(
    repo_url: str,
    issue_number: int,
    plan: TestExecutionPlan,
    ttl_seconds: Optional[int] = None,
    secret: Optional[str] = None,
) -> TestExecutionPlan:
    """
    Sign an execution plan with an HMAC-SHA256 signature and set expiration timestamp.
    If no explicit secret is configured, plan.signature is set to None.
    """
    if not plan.expires_at:
        ttl = ttl_seconds or settings.EXECUTION_PLAN_TTL_SECONDS or 1800
        expires_dt = datetime.now(timezone.utc) + timedelta(seconds=ttl)
        plan.expires_at = expires_dt.isoformat()

    plan.signature = compute_plan_signature(
        repo_url=repo_url,
        issue_number=issue_number,
        plan=plan,
        secret=secret,
    )
    return plan


def verify_execution_plan(
    repo_url: str,
    issue_number: int,
    plan: TestExecutionPlan,
    secret: Optional[str] = None,
) -> tuple[bool, str]:
    """
    Verify the cryptographic integrity and freshness of an execution plan.
    Fails closed if no explicit signing secret is configured on the server.
    """
    secret_bytes = get_signing_secret_bytes(secret)
    if not secret_bytes:
        return False, "Live test execution is disabled: EXECUTION_SIGNING_SECRET is not configured on the server."

    if not plan.signature or not plan.signature.strip():
        return False, "Missing execution plan signature."

    if not plan.expires_at or not plan.expires_at.strip():
        return False, "Missing execution plan expiration timestamp."

    # Validate expiration timestamp
    try:
        exp_clean = plan.expires_at.replace("Z", "+00:00")
        expires_dt = datetime.fromisoformat(exp_clean)
        if expires_dt.tzinfo is None:
            expires_dt = expires_dt.replace(tzinfo=timezone.utc)
    except Exception:
        return False, f"Invalid expiration timestamp format: '{plan.expires_at}'."

    now = datetime.now(timezone.utc)
    if now > expires_dt:
        return False, f"Execution plan expired at {plan.expires_at} (current time: {now.isoformat()})."

    # Compute expected signature and compare with constant time comparison
    expected_signature = compute_plan_signature(
        repo_url=repo_url,
        issue_number=issue_number,
        plan=plan,
        secret=secret,
    )

    if not expected_signature or not hmac.compare_digest(plan.signature, expected_signature):
        return False, "Execution plan signature is invalid or does not match repository/issue context."

    return True, "Execution plan signature verified."
